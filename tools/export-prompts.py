#!/usr/bin/env python3
"""Writes js/ai/prompts.js from serve.py, so the GitHub Pages (no-server) mode uses exactly the same AI instructions
and answer formats as the local server. Run after changing a prompt in serve.py:  python tools/export-prompts.py"""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT); sys.dont_write_bytecode = True
import serve
out = {k: {'system': sy, 'schema': serve.gemini_schema(sc)} for k, (sy, sc, _) in serve.SECTIONS.items()}
with open(os.path.join(ROOT, 'js', 'ai', 'prompts.js'), 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/export-prompts.py from serve.py — do not edit by hand.\n')
    f.write('export const GEMINI_MODELS = ' + json.dumps(serve.GEMINI_MODELS[-2:]) + ';\n')
    f.write('export const SECTIONS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print('js/ai/prompts.js written')
