#!/usr/bin/env python3
"""Regenerates sw.js with the list of every app file to precache (run after changing files)."""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'tools', '.git', 'node_modules', 'docs', 'music', '__pycache__'}
SKIP_FILES = {'sw.js', 'serve.py', 'reset.html', 'orbi_ai_key.txt', 'README.md', '.DS_Store'}
files, h = [], hashlib.sha256()
for d, dirs, fs in os.walk(ROOT):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
    for f in sorted(fs):
        if f in SKIP_FILES or f.endswith(('.txt', '.md')) and 'vendor' not in d: continue
        p = os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/')
        files.append('./' + p)
        with open(os.path.join(d, f), 'rb') as fh: h.update(p.encode()); h.update(fh.read())
version = h.hexdigest()[:10]
sw = f"""// ORBITAL service worker — generated by tools/build-sw.py. Precaches the whole app (incl. CV models) for offline use.
const CACHE = 'orbital-{version}';
const ASSETS = {json.dumps(['./'] + files, indent=0)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('orbital') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  // Network first: when the local server is running you always get the current files (no stale/mixed versions);
  // the cache is only used when the server is unreachable (offline use).
  const req = e.request;
  const u = new URL(req.url);
  if (req.method !== 'GET' || u.origin !== location.origin || /\\/(api|music)\\//.test(u.pathname)) return; // live APIs and audio: never cached
  e.respondWith(fetch(req, {{ cache: 'no-store' }}).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }}).catch(() => caches.open(CACHE).then(c => c.match(req, {{ ignoreSearch: true }})).then(hit => hit || (req.mode === 'navigate' ? caches.match('./index.html') : Response.error()))));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print(f'sw.js written: {len(files)} files, cache orbital-{version}')
